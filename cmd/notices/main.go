// Command notices generates THIRD_PARTY_NOTICES.txt, the license and notice text for
// everything the monitor redistributes: the Go runtime, every module compiled into the
// shipped linux/amd64 and js/wasm builds, and the vendored browser assets. Test-only
// modules are excluded because they are never distributed. Run it with
// `mise run notices`; a test in this package fails when the committed file is stale.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// module identifies one Go module and its location in the module cache.
type module struct {
	path, version, dir string
}

// target is one shipped build: a platform and the packages compiled for it.
type target struct {
	goos, goarch string
	packages     []string
}

// asset is a vendored browser dependency and its repo-relative license files.
type asset struct {
	title string
	files []string
}

// listFormat prints one tab-separated line per package owned by a dependency module.
const listFormat = `{{with .Module}}{{if not .Main}}{{.Path}}{{"\t"}}{{.Version}}{{"\t"}}{{.Dir}}{{end}}{{end}}`

// licenseName matches the license and notice files at a module's root, including
// variants such as LICENSE-3RD-PARTY.md, SQLITE-LICENSE and COPYING.
var licenseName = regexp.MustCompile(`(?i)(licen[cs]e|copying|notice)`)

// shippedBuilds lists what the published image is built from, including the WASM checker
// its certificate pages load.
var shippedBuilds = []target{
	{goos: "linux", goarch: "amd64", packages: []string{"./..."}},
	{goos: "js", goarch: "wasm", packages: []string{"./cmd/wasm"}},
}

// vendoredAssets lists third-party files committed to the repo rather than compiled.
var vendoredAssets = []asset{
	{
		title: "Stoplight Elements 9.0.23 (internal/web/elements.min.*)",
		files: []string{"internal/web/elements.LICENSE", "internal/web/elements.min.js.LICENSE.txt"},
	},
	{
		title: "Readex Pro and JetBrains Mono fonts (internal/web/fonts)",
		files: []string{"internal/web/fonts/OFL.txt"},
	},
}

// main writes the generated notices to the path given by -out.
func main() {
	out := flag.String("out", "THIRD_PARTY_NOTICES.txt", "output file")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	body, err := generate(*root)
	if err == nil {
		err = os.WriteFile(*out, []byte(body), 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

// generate renders the complete notices document for the repository at root.
func generate(root string) (string, error) {
	var b strings.Builder
	b.WriteString("Third-party notices for iscc-monitor\n")
	b.WriteString("Generated by cmd/notices (mise run notices). Do not edit by hand.\n")

	goroot, err := runGo(root, nil, "env", "GOROOT")
	if err != nil {
		return "", err
	}
	if err := writeSection(&b, "Go standard library and runtime (includes wasm_exec.js)",
		[]string{filepath.Join(strings.TrimSpace(goroot), "LICENSE")}); err != nil {
		return "", err
	}

	modules, err := shippedModules(root)
	if err != nil {
		return "", err
	}
	for _, m := range modules {
		files, err := licenseFiles(m.dir)
		if err != nil {
			return "", fmt.Errorf("%s: %w", m.path, err)
		}
		if err := writeSection(&b, m.path+" "+m.version, files); err != nil {
			return "", err
		}
	}

	for _, a := range vendoredAssets {
		files := make([]string, len(a.files))
		for i, f := range a.files {
			files[i] = filepath.Join(root, filepath.FromSlash(f))
		}
		if err := writeSection(&b, a.title, files); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

// shippedModules returns the sorted, unique dependency modules of all shipped builds.
func shippedModules(root string) ([]module, error) {
	var all []module
	for _, t := range shippedBuilds {
		env := []string{"GOOS=" + t.goos, "GOARCH=" + t.goarch, "CGO_ENABLED=0"}
		args := append([]string{"list", "-deps", "-f", listFormat}, t.packages...)
		out, err := runGo(root, env, args...)
		if err != nil {
			return nil, err
		}
		all = append(all, parseModules(out)...)
	}
	return uniqueModules(all), nil
}

// runGo runs the go command in dir with extra environment and returns its stdout.
func runGo(dir string, env []string, args ...string) (string, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), env...)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
	}
	return string(out), nil
}

// parseModules converts listFormat output into modules, skipping blank lines.
func parseModules(out string) []module {
	var modules []module
	for line := range strings.Lines(out) {
		fields := strings.Split(strings.TrimRight(line, "\r\n"), "\t")
		if len(fields) == 3 {
			modules = append(modules, module{path: fields[0], version: fields[1], dir: fields[2]})
		}
	}
	return modules
}

// uniqueModules sorts modules by path and version and removes duplicates.
func uniqueModules(modules []module) []module {
	sorted := slices.Clone(modules)
	slices.SortFunc(sorted, func(a, b module) int {
		return strings.Compare(a.path+" "+a.version, b.path+" "+b.version)
	})
	return slices.Compact(sorted)
}

// licenseFiles returns the sorted license and notice files at the root of dir. A module
// without any is an error, because its redistribution terms would be unknown.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, e := range entries {
		if !e.IsDir() && licenseName.MatchString(e.Name()) {
			files = append(files, filepath.Join(dir, e.Name()))
		}
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no license file in %s", dir)
	}
	slices.Sort(files)
	return files, nil
}

// writeSection appends a titled section holding the normalized text of each file.
func writeSection(b *strings.Builder, title string, files []string) error {
	fmt.Fprintf(b, "\n%s\n%s\n", strings.Repeat("=", 78), title)
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\n--- %s ---\n\n%s\n", filepath.Base(f), normalize(string(data)))
	}
	return nil
}

// normalize makes text identical across platforms: LF line endings, no outer blank lines.
func normalize(text string) string {
	return strings.Trim(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
}
